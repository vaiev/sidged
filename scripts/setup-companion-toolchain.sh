# setup-companion-toolchain.sh: user-local toolchain for companion/ (WP 7), no sudo.
#
#   bash scripts/setup-companion-toolchain.sh [--accept-android-licenses]
#   . "${SIDGED_TOOLCHAIN:-$HOME/.local/share/sidged-toolchain}/env.sh"
#
# Installs, each pinned and checksum-verified before it is unpacked:
#   - Temurin JDK 17 (Android Gradle builds)
#   - Android command-line tools, then platform-tools, platform 35, build-tools 35.0.0
#     and NDK r28c through sdkmanager (which verifies its own downloads)
#   - Rust Android targets for the repository toolchain (rust-toolchain.toml)
#   - tauri-cli 2.11.5 (the last release that builds with rustc 1.89)
#   - with --with-llama: llama.cpp v0.6.0 (commit-pinned) built CPU-only for llama-server,
#     the local model endpoint of the desktop node (scripts/serve-local-linguist.sh)
# Nothing else is installed. The Linux desktop build also needs WebKitGTK headers from
# the distribution; the script only checks for them and prints the apt command.
set -euo pipefail

TOOLCHAIN=${SIDGED_TOOLCHAIN:-$HOME/.local/share/sidged-toolchain}
ANDROID_SDK=${ANDROID_HOME:-$HOME/Android/Sdk}
JDK_URL="https://github.com/adoptium/temurin17-binaries/releases/download/jdk-17.0.20.1%2B1/OpenJDK17U-jdk_x64_linux_hotspot_17.0.20.1_1.tar.gz"
JDK_SHA256=3808d1d15e3ec6bd5b84057fb5d84c33d8a1536a258146bcea2e603fc726e08e
CMDLINE_URL="https://dl.google.com/android/repository/commandlinetools-linux-13114758_latest.zip"
CMDLINE_SHA256=7ec965280a073311c339e571cd5de778b9975026cfcbe79f2b1cdcb1e15317ee
SDK_PACKAGES=("platform-tools" "platforms;android-35" "build-tools;35.0.0" "ndk;28.2.13676358")
RUST_ANDROID_TARGETS=(aarch64-linux-android x86_64-linux-android)
TAURI_CLI_VERSION=2.11.5
LLAMA_TAG=v0.6.0
LLAMA_COMMIT=d81235049384534c167caea52b85a694f6103d14

accept=0
llama=0
for arg in "$@"; do
  case $arg in
    --accept-android-licenses) accept=1 ;;
    --with-llama) llama=1 ;;
    *) echo "usage: $0 [--accept-android-licenses] [--with-llama]" >&2; exit 2 ;;
  esac
done

root=$(cd "$(dirname "$0")/.." && pwd)
mkdir -p "$TOOLCHAIN/downloads" "$ANDROID_SDK"

fetch() { # url sha256 file
  local url=$1 sum=$2 file=$TOOLCHAIN/downloads/$3
  if [[ ! -f $file ]] || ! echo "$sum  $file" | sha256sum -c --status; then
    curl -fsSL --retry 3 -o "$file.part" "$url"
    echo "$sum  $file.part" | sha256sum -c --status || { echo "checksum mismatch: $url" >&2; rm -f "$file.part"; exit 1; }
    mv "$file.part" "$file"
  fi
  echo "$file"
}

jdk_home=$TOOLCHAIN/jdk-17.0.20.1+1
if [[ ! -x $jdk_home/bin/java ]]; then
  archive=$(fetch "$JDK_URL" "$JDK_SHA256" jdk17.tar.gz)
  tar -xzf "$archive" -C "$TOOLCHAIN"
fi

sdkmanager=$ANDROID_SDK/cmdline-tools/latest/bin/sdkmanager
if [[ ! -x $sdkmanager ]]; then
  archive=$(fetch "$CMDLINE_URL" "$CMDLINE_SHA256" cmdline-tools.zip)
  rm -rf "$ANDROID_SDK/cmdline-tools/latest" "$TOOLCHAIN/cmdline-unpack"
  mkdir -p "$ANDROID_SDK/cmdline-tools" "$TOOLCHAIN/cmdline-unpack"
  python3 -I -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' \
    "$archive" "$TOOLCHAIN/cmdline-unpack"
  mv "$TOOLCHAIN/cmdline-unpack/cmdline-tools" "$ANDROID_SDK/cmdline-tools/latest"
  chmod +x "$ANDROID_SDK"/cmdline-tools/latest/bin/*
  rmdir "$TOOLCHAIN/cmdline-unpack"
fi

export JAVA_HOME=$jdk_home
if (( accept )); then
  # `yes` ends with SIGPIPE once sdkmanager stops reading; that is not a failure.
  (set +o pipefail; yes | "$sdkmanager" --sdk_root="$ANDROID_SDK" --licenses >/dev/null)
fi
"$sdkmanager" --sdk_root="$ANDROID_SDK" --install "${SDK_PACKAGES[@]}"

(cd "$root" && rustup target add "${RUST_ANDROID_TARGETS[@]}")
if ! cargo tauri --version 2>/dev/null | grep -qx "tauri-cli $TAURI_CLI_VERSION"; then
  (cd "$root" && cargo install tauri-cli --version "=$TAURI_CLI_VERSION" --locked)
fi

if (( llama )); then
  src=$TOOLCHAIN/llama.cpp
  if [[ ! -d $src/.git ]]; then
    git clone -q --depth 1 --branch "$LLAMA_TAG" https://github.com/ggml-org/llama.cpp.git "$src"
  fi
  [[ $(git -C "$src" rev-parse HEAD) == "$LLAMA_COMMIT" ]] || { echo "llama.cpp is not at $LLAMA_COMMIT" >&2; exit 1; }
  command -v cmake >/dev/null || { echo "cmake is required for --with-llama (e.g. pip install cmake==4.4.4)" >&2; exit 1; }
  cmake -S "$src" -B "$src/build" -DGGML_CUDA=OFF -DLLAMA_CURL=OFF -DGGML_NATIVE=ON \
    -DLLAMA_BUILD_TESTS=OFF -DLLAMA_BUILD_EXAMPLES=OFF -DCMAKE_BUILD_TYPE=Release >/dev/null
  cmake --build "$src/build" --target llama-server -j "$(nproc)" >/dev/null
fi

cat > "$TOOLCHAIN/env.sh" <<EOF
# Generated by scripts/setup-companion-toolchain.sh
export JAVA_HOME="$jdk_home"
export ANDROID_HOME="$ANDROID_SDK"
export NDK_HOME="$ANDROID_SDK/ndk/28.2.13676358"
export PATH="\$JAVA_HOME/bin:\$ANDROID_HOME/platform-tools:\$ANDROID_HOME/cmdline-tools/latest/bin:\$HOME/.cargo/bin:\$PATH"
EOF

if ! pkg-config --exists webkit2gtk-4.1 2>/dev/null; then
  echo "Linux desktop builds need WebKitGTK (one time, with sudo):"
  echo "  sudo apt install -y libwebkit2gtk-4.1-dev build-essential pkg-config libssl-dev libxdo-dev libayatana-appindicator3-dev librsvg2-dev file"
fi
echo "toolchain ready: . $TOOLCHAIN/env.sh"
